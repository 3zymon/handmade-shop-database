CREATE TABLE KLIENT (
	ID_KLIENT BIGSERIAL PRIMARY KEY,
	IMIE VARCHAR(50) NOT NULL,
	NAZWISKO VARCHAR(100) NOT NULL,
	EMAIL VARCHAR(254) UNIQUE NOT NULL,
	NR_TELEFONU VARCHAR(20) UNIQUE NOT NULL,
	ULICA VARCHAR(150),
	NR_DOMU_MIESZKANIA VARCHAR(20),
	KOD_POCZTOWY VARCHAR(10),
	MIASTO VARCHAR(100),
	KRAJ VARCHAR(100)
);

CREATE TABLE PRACOWNIK (
	ID_PRACOWNIK BIGSERIAL PRIMARY KEY,
	STANOWISKO VARCHAR(150) NOT NULL,
	IMIE VARCHAR(50) NOT NULL,
	NAZWISKO VARCHAR(100) NOT NULL,
	EMAIL VARCHAR(254) UNIQUE NOT NULL,
	NR_TELEFONU VARCHAR(20) UNIQUE NOT NULL,
	ULICA VARCHAR(150),
	NR_DOMU_MIESZKANIA VARCHAR(20),
	KOD_POCZTOWY VARCHAR(10),
	MIASTO VARCHAR(100),
	KRAJ VARCHAR(100)
);

CREATE TABLE PRODUKT (
	ID_PRODUKT BIGSERIAL PRIMARY KEY,
	NAZWA VARCHAR(50) NOT NULL,
	KATEGORIA VARCHAR(50) NOT NULL,
	CENA DECIMAL(10, 2) CHECK (CENA >= 0) NOT NULL,
	KOLOR VARCHAR(50) NOT NULL
);

CREATE TABLE MATERIAL (
	ID_MATERIAL BIGSERIAL PRIMARY KEY,
	NAZWA VARCHAR(50) NOT NULL,
	KATEGORIA VARCHAR(50) NOT NULL,
	CENA DECIMAL(10, 2) NOT NULL CHECK (CENA >= 0),
	DOSTAWCA VARCHAR(150) NOT NULL,
	ILOSC_MAGAZYNIE INT NOT NULL DEFAULT 0 CHECK (ILOSC_MAGAZYNIE >= 0)
);

CREATE TABLE ZAMOWIENIE (
	ID_ZAMOWIENIE BIGSERIAL PRIMARY KEY,
	ID_KLIENT BIGINT NOT NULL REFERENCES KLIENT (ID_KLIENT),
	ID_PRACOWNIK BIGINT NOT NULL REFERENCES PRACOWNIK (ID_PRACOWNIK),
	DATA_ZAMOWIENIA TIMESTAMP NOT NULL,
	DATA_SPAKOWANIA TIMESTAMP,
	DATA_WYSLANIA TIMESTAMP,
	STATUS_ZAMOWIENIA VARCHAR(30) NOT NULL,
	CENA_ZAMOWIENIA DECIMAL(10, 2) NOT NULL CHECK (CENA_ZAMOWIENIA > 0)
);

CREATE TABLE PLATNOSCI (
	NR_PLATNOSCI BIGSERIAL PRIMARY KEY,
	ID_ZAMOWIENIE BIGINT NOT NULL REFERENCES ZAMOWIENIE (ID_ZAMOWIENIE),
	METODA_PLATNOSCI VARCHAR(30),
	STATUS_PLATNOSCI VARCHAR(30) NOT NULL,
	KWOTA_PLATNOSCI DECIMAL(10, 2) CHECK (KWOTA_PLATNOSCI >= 0),
	DATA_PLATNOSCI TIMESTAMP
);

CREATE TABLE ZAMOWIONY_PRODUKT (
	ID_ZAMOWIENIE BIGINT NOT NULL REFERENCES ZAMOWIENIE (ID_ZAMOWIENIE),
	ID_PRODUKT BIGINT NOT NULL REFERENCES PRODUKT (ID_PRODUKT),
	ILOSC_PRODUKTU INT NOT NULL CHECK (ILOSC_PRODUKTU > 0),
	PRIMARY KEY (ID_ZAMOWIENIE, ID_PRODUKT)
);

CREATE TABLE MATERIAL_PRODUKTU (
	ID_PRODUKT BIGINT NOT NULL REFERENCES PRODUKT (ID_PRODUKT),
	ID_MATERIAL BIGINT NOT NULL REFERENCES MATERIAL (ID_MATERIAL),
	ILOSC INT NOT NULL CHECK (ILOSC > 0),
	PRIMARY KEY (ID_PRODUKT, ID_MATERIAL)
);